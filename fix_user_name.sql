-- إصلاح اسم المستخدم من "هيدر علي" إلى "حيدر علي"
-- شغّل هذا السكربت مرة واحدة على قاعدة بيانات PostgreSQL
-- الاتصال من: appsettings.json → DefaultConnection
-- (Database=smartgasstationsimpledb)
-- ملاحظة: PostgreSQL حساس لحالة الأحرف، أسماء الأعمدة PascalCase
-- لذا يجب إحاطتها بعلامات اقتباس مزدوجة "Name" بدلاً من Name
-- ============================================================

-- قبل التعديل: عرض السجلات التي ستحتوي على "هيدر" لمراجعتها
SELECT "Id", "Name", "Email", "Role", "Status"
FROM users
WHERE "Name" LIKE '%هيدر%';

-- تنفيذ التعديل: استبدال "هيدر" بـ "حيدر" في كل السجلات المطابقة
UPDATE users
SET "Name" = REPLACE("Name", 'هيدر', 'حيدر')
WHERE "Name" LIKE '%هيدر%';

-- بعد التعديل: تحقق أن التحويل تم بنجاح
SELECT "Id", "Name", "Email", "Role", "Status"
FROM users
WHERE "Name" LIKE '%حيدر%' OR "Name" LIKE '%هيدر%';

-- ============================================================
-- ملاحظات:
-- 1. إذا كان الاسم بالعربية فقط "هيدر علي" فستجده الآن "حيدر علي".
-- 2. لا حاجة لإعادة تشغيل الخادم — الواجهة ستعرض الاسم الجديد عند التحديث التالي.
-- 3. هذا السكربت آمن: UPDATE يطابق فقط الأسماء التي تحتوي على "هيدر"،
--    فلن يمس أي سجل آخر.
-- 4. إذا فشل التعديل بسبب تكرار قيد فريد على حقل آخر، أخبرني بالخطأ.
-- ============================================================